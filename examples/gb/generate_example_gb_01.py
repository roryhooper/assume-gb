DEMAND_PRICE = 3000.0
PRICE_CAP = 3000.0
GAS_MC = GAS_PRICE / GAS_EFFICIENCY + CO2_PRICE * GAS_EMISSION_FACTOR / GAS_EFFICIENCY

SEQUENTIAL_MARKETS = ["DA", "ID", "BAL"]

